#!/usr/bin/env bash
#
# Cloud Agent start phase (per boot).
# 1. Ensures a MongoDB is reachable (a local mongod unless MONGODB_URI is provided).
# 2. Writes the repo-root .env that `npm run dev` (env-cmd) requires.
# Idempotent and non-blocking: it starts background services, waits for readiness,
# then returns. The Next.js dev server runs from the `next-dev` terminal.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

# --- MongoDB -----------------------------------------------------------------
# Prefer an externally provided MONGODB_URI (e.g. Atlas via a secret). Otherwise
# run a self-contained local mongod so the app works with no external services.
if [ -n "${MONGODB_URI:-}" ]; then
  MONGO_URI="$MONGODB_URI"
  echo "[start] Using provided MONGODB_URI."
else
  MONGO_URI="mongodb://127.0.0.1:27017"
  DATA_DIR="$REPO_ROOT/.cursor/mongo-data"
  LOG_DIR="$REPO_ROOT/.cursor/mongo-logs"
  mkdir -p "$DATA_DIR" "$LOG_DIR"

  if pgrep -x mongod >/dev/null 2>&1; then
    echo "[start] Local mongod already running."
  else
    echo "[start] Starting local mongod…"
    mongod --dbpath "$DATA_DIR" --bind_ip 127.0.0.1 --port 27017 \
      --logpath "$LOG_DIR/mongod.log" --fork >/dev/null
  fi

  echo "[start] Waiting for MongoDB to accept connections…"
  for _ in $(seq 1 30); do
    if mongosh --quiet --norc "$MONGO_URI" --eval 'db.runCommand({ ping: 1 }).ok' >/dev/null 2>&1; then
      echo "[start] MongoDB is ready."
      break
    fi
    sleep 1
  done
fi

# --- AUTH_SECRET -------------------------------------------------------------
# Use a provided AUTH_SECRET when available; otherwise generate one and persist
# it so sessions/invites remain stable across reboots of this environment.
AUTH_SECRET_VALUE="${AUTH_SECRET:-}"
if [ -z "$AUTH_SECRET_VALUE" ]; then
  SECRET_FILE="$REPO_ROOT/.cursor/.auth-secret"
  if [ ! -f "$SECRET_FILE" ]; then
    openssl rand -base64 32 >"$SECRET_FILE"
  fi
  AUTH_SECRET_VALUE="$(cat "$SECRET_FILE")"
fi

# --- .env (required by env-cmd in `npm run dev`) -----------------------------
ENV_FILE="$REPO_ROOT/.env"
{
  echo "# Auto-generated by .cursor/start.sh on each boot. Do not commit."
  echo "MONGODB_URI=$MONGO_URI"
  echo "DB_NAME=${DB_NAME:-decision-copilot-evals}"
  echo "AUTH_SECRET=$AUTH_SECRET_VALUE"
  echo "AUTH_URL=${AUTH_URL:-http://localhost:5002}"
  echo "NEXTAUTH_URL=${NEXTAUTH_URL:-http://localhost:5002}"
  # Pass through any optional provider / integration secrets that are set.
  for key in \
    OPENAI_API_KEY ANTHROPIC_API_KEY GEMINI_API_KEY XAI_API_KEY \
    OPENAI_MODEL OPENAI_WEB_SEARCH_MODEL ANTHROPIC_MODEL XAI_MODEL \
    GOOGLE_CLIENT_ID GOOGLE_CLIENT_SECRET INVITE_SECRET \
    SLACK_INVITE_ALERT_WEBHOOK_URL; do
    value="${!key:-}"
    if [ -n "$value" ]; then
      echo "$key=$value"
    fi
  done
} >"$ENV_FILE"

echo "[start] Wrote $ENV_FILE"
echo "[start] Done."
